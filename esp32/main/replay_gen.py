#!/usr/bin/env python3
"""
Generate esp32/main/replay_frames.h from a PC-captured frames.bin
(tools/run_baseline.sh layout: RGB565 320x240, 153 600 B per frame,
little-endian pairs) so the ESP32 panel replay matches the PC reference
exactly.

usage: replay_gen.py <frames.bin> [nframes=8]

The header is not committed; it compiles the pixels into .rodata
(flash). Keep nframes small — an 8-frame embed is ~1.2 MB inside the
app image; the default 3 MB app partition holds ~15 frames.
"""

import os
import sys

PANEL_W, PANEL_H = 320, 240
FRAME_BYTES = PANEL_W * PANEL_H * 2
PIXELS = PANEL_W * PANEL_H


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    src = sys.argv[1]
    n = int(sys.argv[2]) if len(sys.argv) > 2 else 8

    size = os.path.getsize(src)
    have = size // FRAME_BYTES
    n = min(n, have)
    if n == 0:
        sys.exit(f"{src}: no complete frames (size {size})")

    out_dir = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(out_dir, "replay_frames.h")

    with open(src, "rb") as f:
        data = f.read(n * FRAME_BYTES)

    def words_for(frame):
        words = [int.from_bytes(frame[j:j+2], "little")
                 for j in range(0, FRAME_BYTES, 2)]
        rows = []
        for i in range(0, len(words), 8):
            # Trailing comma on every row: a comma is required BETWEEN
            # rows too (join only puts separators between, and the C99
            # trailing comma before '}' is legal).
            rows.append("    " + ", ".join("0x%04X" % w for w in words[i:i+8]) + ",")
        return "\n".join(rows)

    chunks = []
    for k in range(n):
        frame = data[k*FRAME_BYTES:(k+1)*FRAME_BYTES]
        chunks.append(
            "/* frame %d */\n"
            "static const uint16_t jc_frame_%d[%d] = {\n%s\n};"
            % (k, k, PIXELS, words_for(frame)))

    header = (
        "/* Generated by esp32/main/replay_gen.py from %s (first %d of %d\n"
        " * captured frames; see esp32/README.md). Do not edit. */\n"
        "#pragma once\n"
        "#define JC_REPLAY_NFRAMES %d\n\n"
        "static const uint16_t *jc_replay_frames[%d] = {\n    %s\n};\n"
        % (src, n, have, n, n, ", ".join("jc_frame_%d" % i for i in range(n))))

    with open(out, "w") as f:
        f.write("\n\n".join(chunks) + "\n\n" + header + "\n")

    print(f"wrote {out} ({n} frames, {n * FRAME_BYTES // 1024} KiB of footage)")


if __name__ == "__main__":
    main()
